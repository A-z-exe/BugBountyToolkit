"""Report generation: human-readable Markdown and machine-readable JSON."""
from __future__ import annotations

import datetime
import json
from pathlib import Path
from typing import Dict, List, Tuple

from . import __version__
from .context import ScanContext
from .findings import SEVERITIES


def _relative(path: str, base: Path) -> str:
    try:
        return str(Path(path).relative_to(base)).replace("\\", "/")
    except (ValueError, TypeError):
        return Path(path).name


def render_markdown(ctx: ScanContext, mode: str, duration: float) -> str:
    counts = ctx.findings.counts()
    target = ctx.target
    lines: List[str] = []

    lines.append("# Security Assessment Report\n")
    lines.append(f"- **Target:** `{target.display}`")
    lines.append(f"- **Mode:** `{mode}`")
    lines.append(
        f"- **Date:** {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    )
    lines.append(f"- **Duration:** {duration:.1f}s")
    lines.append(f"- **Generated by:** BBT v{__version__}\n")

    lines.append("## Executive Summary\n")
    total = len(ctx.findings)
    if total == 0:
        lines.append("No findings were recorded by the automated checks. "
                     "This does **not** mean the target is secure.\n")
    else:
        lines.append(f"The automated assessment produced **{total}** finding(s):\n")
        lines.append("| Severity | Count |")
        lines.append("|----------|-------|")
        for severity in SEVERITIES:
            lines.append(f"| {severity.title()} | {counts[severity]} |")
        lines.append("")

    lines.append("## Findings\n")
    if total == 0:
        lines.append("_None._\n")
    for finding in ctx.findings.sorted():
        lines.append(
            f"### [{finding.severity.upper()}] {finding.title}\n"
        )
        lines.append(f"- **Target:** `{finding.target}`")
        lines.append(f"- **Category:** {finding.category}")
        lines.append(f"- **Confidence:** {finding.confidence}")
        if finding.description:
            lines.append(f"\n{finding.description}\n")
        if finding.evidence:
            lines.append("```text")
            lines.append(finding.evidence)
            lines.append("```")
        if finding.remediation:
            lines.append(f"**Remediation:** {finding.remediation}\n")
        if finding.references:
            lines.append("**References:**")
            for ref in finding.references:
                lines.append(f"- {ref}")
            lines.append("")

    lines.append("## Artifacts\n")
    if ctx.artifacts:
        for key, path in sorted(ctx.artifacts.items()):
            lines.append(f"- **{key}**: [{_relative(path, ctx.output_dir)}]({_relative(path, ctx.output_dir)})")
    else:
        lines.append("_No artifacts produced._")
    lines.append("")

    lines.append("## Methodology\n")
    lines.append(
        "The assessment combines non-intrusive checks (headers, cookies, TLS, CORS, "
        "content discovery, network port scanning) with clearly-labelled heuristic "
        "probes. Every finding must be verified manually before it is treated as a "
        "real vulnerability.\n"
    )

    lines.append("## Disclaimer\n")
    lines.append(
        "This report was produced by an automated tool for authorized testing only. "
        "Only test systems you own or have explicit written permission to test. "
        "Automated results can contain false positives and false negatives.\n"
    )
    return "\n".join(lines)


def write_reports(ctx: ScanContext, mode: str, duration: float) -> Tuple[Path, Path]:
    md_path = ctx.artifact("SECURITY_REPORT.md")
    md_path.write_text(render_markdown(ctx, mode, duration), encoding="utf-8")

    summary: Dict[str, object] = {
        "tool": "BBT",
        "version": __version__,
        "generated_at": datetime.datetime.now().isoformat(),
        "mode": mode,
        "duration_seconds": round(duration, 2),
        "target": ctx.target.to_dict(),
        "summary": ctx.findings.counts(),
        "total_findings": len(ctx.findings),
        "findings": ctx.findings.to_list(),
        "artifacts": {
            key: _relative(path, ctx.output_dir)
            for key, path in ctx.artifacts.items()
        },
    }
    json_path = ctx.artifact("scan_summary.json")
    json_path.write_text(
        json.dumps(summary, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )
    return md_path, json_path


def write_session_summary(session_dir: Path, results: List[Dict[str, object]]) -> Path:
    path = session_dir / "session_summary.json"
    payload = {
        "tool": "BBT",
        "version": __version__,
        "generated_at": datetime.datetime.now().isoformat(),
        "targets": results,
    }
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )
    return path
